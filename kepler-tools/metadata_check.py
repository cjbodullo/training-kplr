#!/usr/bin/env python3
"""Pre-submit gate for the metadata the quality review blocks on.

Every check here corresponds to a criterion that has actually failed a submission on this
account, so it is cheap insurance against a round trip. Run from the repo root:

    python3 kepler-tools/metadata_check.py task-src/<slug>
"""
import pathlib
import re
import sys
import tomllib

ROLE_HINTS = ("this is the job of", "the job of the", "engineer who", "the work of",
              "a practitioner", "who owns", "responsible for")
# only a statement that the data was MADE counts. "planted", "seeded" and the like describe
# what is in it, not where it came from, and the judge reads the difference.
PROVENANCE_HINTS = ("synthetic", "synthetically", "generated by", "generated deterministically",
                    "generator", "seedgen", "fabricated", "not real data")
AGENT_PHRASES = ("the agent", "agents ", "frontier agent", "solve rate", "llm ", "the model ")
SUFFIX = ("You have {n} seconds to complete this task. Do not cheat by using online "
          "solutions or hints specific to this task.")


def main(root):
    root = pathlib.Path(root)
    toml = tomllib.load(open(root / "task.toml", "rb"))
    meta = toml.get("metadata", {})
    errs, warns = [], []

    diff = meta.get("difficulty_explanation", "")
    low = diff.lower()

    if not any(h in low for h in ROLE_HINTS):
        errs.append("difficulty_explanation: no sentence naming who does this work in the "
                    "real world (having it in relevant_experience does not count)")

    ships_generator = any(p.name.endswith(".py") and "gen" in p.name
                          for p in (root / "environment").rglob("*.py"))
    ships_data = any((root / "environment").rglob(g) for g in ("*.csv", "*.json", "*.gz",
                                                               "*.tsv", "*.ndjson"))
    if (ships_generator or ships_data) and not any(h in low for h in PROVENANCE_HINTS):
        errs.append("difficulty_explanation: the bundle ships generated or sample data and "
                    "the explanation never says it is synthetic, what made it, or how "
                    "realistic it is -- a NAMED blocking reason on settlement-rollup and "
                    "order-key-repair")
    for phrase in AGENT_PHRASES:
        if phrase in low:
            errs.append("difficulty_explanation: contains an agent-behaviour claim (%r); the "
                        "criterion wants intrinsic difficulty only" % phrase)

    if re.search(r"\breal (data|volume|estate|corpus|traffic)\b", low):
        warns.append("difficulty_explanation: says 'real data/volume', which reads as a claim "
                     "that the estate is not synthetic -- say the software is real and the "
                     "data is generated")

    hours = meta.get("expert_time_estimate_hours")
    budget = toml.get("agent", {}).get("timeout_sec")
    if hours and budget and hours * 3600 > budget:
        errs.append("expert_time_estimate_hours (%s h) exceeds the agent budget (%.1f h)"
                    % (hours, budget / 3600))

    text = (root / "instruction.md").read_text()
    want = SUFFIX.format(n=int(budget)) if budget else None
    if want and not text.endswith("\n" + want + "\n"):
        errs.append("instruction.md does not end with a blank line, the exact suffix for "
                    "N=%d, and one trailing newline" % int(budget))

    for label, field in (("solution", "solution_explanation"),
                         ("verification", "verification_explanation")):
        if not meta.get(field):
            errs.append("%s_explanation is missing" % label)

    for e in errs:
        print("ERROR   %s" % e)
    for w in warns:
        print("warning %s" % w)
    if not errs and not warns:
        print("metadata checks: clean")
    print("\nStill yours to check by hand: every number in the three explanations must be "
          "re-derived from the sealed data after the last regeneration.")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "."))
