#!/usr/bin/env python3
"""
Humanize text using humanizeai.pro (working params).

Usage:
    python3 humanize.py <input_file> [output_file]   # humanize a file (in place if no output)
    python3 humanize.py --test                        # smoke test the API

For Kepler instructions, protect the must-stay-exact tokens (code identifiers,
literal values, absolute paths) by wrapping them in backticks, and protect the
required timeout suffix line with --keep-last-line so it is re-appended verbatim.
Score < 0.5 means more human-like.

Requires: pip install --user --break-system-packages curl_cffi
"""

import sys
import json
import re
import time
import random
import string
from pathlib import Path
from curl_cffi import requests

API_BASE = "https://www.humanizeai.pro"
API_ENDPOINT = f"{API_BASE}/api/process"

# WORKING params (see the parameter table — the broken script used alg=1,
# style="casual", sessionId=None, keywords="" which 400s or degrades output).
BASE_PARAMS = {
    "alg": 0,
    # valid styles: standard|academic|simple|flowing|informal|formal|expand|shorten
    # (the API no longer accepts "free"). "informal" reads most human for dev tickets.
    "style": "informal",
    "isLogged": False,
    "ultra": 0,
    "isSample": False,
    "trialNumber": 0,
    "sessionId": None,          # set to a fresh random 24-char string per call
    "keywords": [],
    "test_limitNot": "true",    # string, not boolean
    "test_allUltra": None,
}

HEADERS = {
    "Content-Type": "application/json",
    "Origin": API_BASE,
    "Referer": f"{API_BASE}/",
}


def _new_sid():
    return "".join(random.choices(string.ascii_lowercase + string.digits, k=24))


def _protect(text):
    """Replace fenced + inline code spans with placeholders so the humanizer
    leaves them untouched. Returns (protected_text, placeholders)."""
    placeholders = []

    def add(m):
        idx = len(placeholders)
        placeholders.append(m.group(0))
        return f"XYZPH{idx:04d}ZYX"

    text = re.sub(r"```.*?```", add, text, flags=re.DOTALL)
    text = re.sub(r"`[^`]+`", add, text)
    return text, placeholders


def _restore(text, placeholders):
    for i, original in enumerate(placeholders):
        text = text.replace(f"XYZPH{i:04d}ZYX", original)
    return text


def _make_session():
    session = requests.Session(impersonate="chrome136")
    resp = session.get(API_BASE, timeout=30)  # required: hit homepage first
    if resp.status_code != 200:
        raise RuntimeError(f"homepage returned {resp.status_code}")
    return session


def _call(session, text):
    payload = {**BASE_PARAMS, "sessionId": _new_sid(), "text": text}
    resp = session.post(API_ENDPOINT, json=payload, headers=HEADERS, timeout=120)
    if resp.status_code != 200:
        raise RuntimeError(f"HTTP {resp.status_code}: {resp.text[:300]}")
    data = resp.json()
    if "error" in data:
        raise RuntimeError(f"API error: {data['error']}")
    result = data.get("result", [{}])[0]
    out = result.get("text", "")
    scores = result.get("scores", {}) or {}
    if not out:
        raise RuntimeError(f"empty result: {json.dumps(data)[:300]}")
    return out, scores


def humanize(text, keep_last_line=False):
    """Humanize text. Code spans are protected. If keep_last_line, the final
    non-empty line (e.g. the required timeout suffix) is split off and
    re-appended verbatim so the humanizer never touches it."""
    suffix = ""
    if keep_last_line:
        lines = text.rstrip("\n").split("\n")
        suffix = lines[-1]
        body = "\n".join(lines[:-1]).rstrip("\n")
    else:
        body = text

    protected, placeholders = _protect(body)

    session = None
    for attempt in range(3):
        try:
            session = _make_session()
            break
        except Exception as e:
            if attempt == 2:
                raise
            time.sleep(4 * (attempt + 1))

    out, scores = None, {}
    for attempt in range(3):
        try:
            out, scores = _call(session, protected)
            break
        except Exception as e:
            if attempt == 2:
                raise
            time.sleep(3 * (attempt + 1))
            try:
                session = _make_session()
            except Exception:
                pass

    out = _restore(out, placeholders)
    if keep_last_line:
        out = out.rstrip("\n") + "\n\n" + suffix + "\n"
    return {"humanized": out, "scores": scores}


def main():
    args = [a for a in sys.argv[1:] if a != "--keep-last-line"]
    keep = "--keep-last-line" in sys.argv

    if not args:
        print(f"usage: {sys.argv[0]} <input_file> [output_file] [--keep-last-line]")
        print(f"       {sys.argv[0]} --test")
        sys.exit(1)

    if args[0] == "--test":
        r = humanize("This is a test sentence generated by artificial intelligence.")
        print(f"scores: {r['scores']}")
        print(f"output: {r['humanized']}")
        return

    inp = Path(args[0])
    out = Path(args[1]) if len(args) > 1 else inp
    if not inp.exists():
        print(f"error: {inp} not found")
        sys.exit(1)

    text = inp.read_text()
    print(f"input: {inp} ({len(text)} chars)")
    r = humanize(text, keep_last_line=keep)
    s = r["scores"]
    print(f"scores: passed_filter={s.get('passed_filter')} "
          f"fallback_to_original={s.get('fallback_to_original')} char8_sim={s.get('char8_sim')}")
    out.write_text(r["humanized"])
    print(f"written: {out}")


if __name__ == "__main__":
    main()
